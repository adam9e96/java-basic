package chapter19_InnerClass;

/**
 * {@code A} 클래스는 내부 클래스 {@code B}를 포함하는 외부 클래스입니다.
 *
 * <p>{@code B} 클래스는 {@code A} 클래스의 인스턴스 멤버 클래스(내부 클래스)로,
 * {@code A} 클래스의 인스턴스 필드 및 메서드 내에서 사용할 수 있습니다.</p>
 *
 * <p>내부 클래스 {@code B}는 외부 클래스 {@code A}와 강하게 결합되어 있으며,
 * {@code A} 클래스의 멤버에 쉽게 접근할 수 있습니다.</p>
 *
 * @author Your Name
 * @version 1.0
 * @since 2024-01-26
 */
class A {

    /**
     * {@code B} 클래스는 {@code A} 클래스의 인스턴스 멤버 클래스입니다.
     *
     * <p>{@code B} 클래스는 외부 클래스 {@code A}의 인스턴스 필드, 생성자, 메서드에서 사용됩니다.</p>
     */
    class B {
        // 내부 클래스 B의 내용
    }

    /**
     * {@code A} 클래스의 인스턴스 필드로 {@code B} 클래스의 객체를 저장합니다.
     */
    B field = new B();

    /**
     * {@code A} 클래스의 생성자입니다.
     *
     * <p>생성자 내부에서 {@code B} 클래스의 객체를 생성하는 예시입니다.</p>
     */
    public A() {
        B b = new B(); // 생성자에서 내부 클래스 B의 객체 생성
    }

    /**
     * {@code A} 클래스의 인스턴스 메서드입니다.
     *
     * <p>메서드 내부에서 {@code B} 클래스의 객체를 생성하는 예시입니다.</p>
     */
    void method() {
        B b = new B(); // 메서드에서 내부 클래스 B의 객체 생성
    }
}

/**
 * {@code InnerClass00} 클래스는 {@code A} 클래스와 {@code B} 클래스의 사용을 보여주는 예제입니다.
 *
 * <p>이 클래스에서는 {@code A} 클래스의 객체를 생성하고, 이를 통해 {@code B} 클래스의 객체를 생성합니다.</p>
 *
 * @author Your Name
 * @version 1.0
 * @since 2024-01-26
 */
public class InnerClass01 {

    /**
     * 프로그램의 진입점으로, {@code A} 클래스 및 {@code B} 클래스의 객체를 생성하여 사용하는 예제입니다.
     */
    public static void main(String[] args) {

        // A 객체 생성
        A a = new A();

        // B 객체 생성
        A.B b = a.new B();
    }
}

/*
 * 클래스 A 안에 내부 클래스 B가 정의되어 있습니다.
 * 내부 클래스 B는 A 클래스의 인스턴스 멤버 클래스입니다.
 *
 * 내부 클래스 B
 * 정의: 내부 클래스 B는 클래스 A의 인스턴스 멤버로, A 클래스 안에 정의되어 있습니다.
 * 사용:
 * 클래스 A의 인스턴스 필드로 사용됩니다.
 * 클래스 A의 생성자와 메소드에서도 객체로 생성됩니다.
 *
 * 외부 클래스 A
 * 필드: B 타입의 인스턴스 필드 field가 있습니다.
 * 생성자: 생성자 안에서 B 클래스의 객체를 생성합니다.
 * 메소드: 인스턴스 메소드 안에서도 B 클래스의 객체를 생성합니다.
 *
 * 내부 클래스는 주로 외부 클래스와 강하게 결합된 상황에서 사용되며,
 * 외부 클래스의 멤버들에 쉽게 접근하고 활용할 수 있도록 설계됩니다.
 */
